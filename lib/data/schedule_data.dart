import 'package:flutter/material.dart';

/// Satu posisi pembalap pada sebuah balapan (P1 - P22).
class RacePodium {
  final String driverCode; // contoh: 'RUS'
  final String result; // P1: waktu total, P2+: selisih atau status (DNF/DNS)
  final int? laps;
  final int? points;
  final String? positionText;

  const RacePodium(
    this.driverCode,
    this.result, {
    this.laps,
    this.points,
    this.positionText,
  });
}

/// Satu balapan pada kalender F1 2026.
class ScheduleRace {
  final int round;
  final String countryCode; // kode ISO 2 huruf, untuk nama file bendera
  final String countryName;
  final String dateRange;
  final String raceName;
  final String flagUrl;
  final String trackImageUrl;
  final List<RacePodium> podium; // urut P1 - P22

  const ScheduleRace({
    required this.round,
    required this.countryCode,
    required this.countryName,
    required this.dateRange,
    required this.raceName,
    required this.flagUrl,
    required this.trackImageUrl,
    required this.podium,
  });

  /// URL PNG flagcdn agar dapat langsung dimuat oleh Image.network.
  String get rasterFlagUrl => flagUrl.endsWith('.svg')
      ? flagUrl
          .replaceFirst('https://flagcdn.com/', 'https://flagcdn.com/w160/')
          .replaceFirst('.svg', '.png')
      : flagUrl;
}

